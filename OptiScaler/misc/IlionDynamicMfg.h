#pragma once

// ILION: one layer over the frame generation providers for Dynamic MFG and its FPS target, so the menu shows the same
// controls and the same state whichever provider generates. It maps to the settings each backend already reads; it
// adds no controller and no limiter of its own:
//   XeFG (ILION's output)      Dynamic = R3 controller (XeFG_DynamicMFG), count changed live by ILION
//   DLSSG of the game          Dynamic = Streamline eDynamic, run by the backend (NVIDIA or a replacement such as
//   (NvngxFG, DLSS Enabler...)  DLSS Enabler) only when it reports support; ILION sets mode and target, the
//                               backend keeps its own maximum and holds the target itself (no ILION cap then)
//   DLSSG (ILION's output)     Dynamic = Streamline eDynamic of ILION's own instance, when it reports support
//   FSR FG                     no Dynamic (one generated frame)
// The target cap goes to the one limiter already in use (Reflex, XeLL or OptiScaler's), as FrameLimit::targetFps().

namespace IlionDynamicMfg
{
enum class Provider
{
    None,
    XeFG,
    DlssgGame,   // the game's DLSSG through Streamline, generated by NVIDIA's runtime or a replacement
    DlssgOutput, // ILION's own DLSSG output
    FsrFg,       // ILION's FSR FG output (and reprojection)
};

enum class Gen
{
    Off,       // nothing generates
    Unknown,   // a generator is loaded but nothing tells whether it runs
    Detected,  // generation is asked for (ILION dispatches, or the game's DLSSG evaluates with frames to generate)
    Confirmed, // the provider reports frames it presented (XeFG present status, Streamline frames presented)
};

// Where an applied multiplier comes from
enum class AppliedSource
{
    None,
    Own,       // ILION's own output: what it applies
    Measured,  // the game's DLSSG: presents per real frame counted at the wrapped swapchain
    Reported,  // unused: Streamline's numFramesActuallyPresented is a count since the game's last query (reported)
    Requested, // only what was asked for: not confirmed
};

enum class Limiter
{
    None,
    Reflex,
    XeLL,
    OptiScaler,
};

struct Status
{
    Provider provider = Provider::None;
    const char* name = "";   // provider, as shown
    Gen gen = Gen::Off;
    bool own = false;        // generated by ILION's pipeline (else by the game / an external backend)
    int multiplier = 0;      // applied: ILION's own, or the game's DLSSG as measured / reported / asked, 0 unknown
    int requested = 0;       // asked for (the game's DLSSG: DLSSG.MultiFrameCount + 1)
    int reported = 0;        // the game's DLSSG: frames its backend says it presented since the game's last query
    AppliedSource appliedSource = AppliedSource::None;
    bool capWaiting = false; // "Use target as cap" on, but the game's DLSSG multiplier isn't confirmed yet: not applied
    bool backendDynamic = false; // the game's DLSSG runs in Streamline eDynamic: its backend chooses multiplier and max
    bool capByBackend = false;   // "Use target as cap" on, not applied by ILION: the backend's Dynamic owns the target
    bool capSuspended = false;   // "Use target as cap" on, suspended: the backend applied more than asked under the cap
    bool ilionDrives = false;    // the game's DLSSG: ILION Dynamic picks its count (eOn)
    const char* ilionRefused = nullptr; // the game's DLSSG: why ILION Dynamic stopped, nullptr when it didn't
    float baseFps = 0.0f;
    bool baseMeasured = false;
    float finalFps = 0.0f;
    bool finalMeasured = false; // else estimated as base x multiplier
    Limiter limiter = Limiter::None;
    float limitFps = 0.0f;   // final frames per second the limiter holds, 0 none
};

Provider Current();

// Dynamic for the current provider: whether it can run, and why not (English, translated by the menu)
bool DynamicSupported(const char** reason = nullptr);
bool DynamicEnabled();
void SetDynamicEnabled(bool enabled);

// Final FPS target shared by every provider (0 = automatic where the provider has one)
float TargetFps();
void SetTargetFps(float fps);

// Highest multiplier as interpolated frames (1 = 2X), and the most the provider admits now (0 = unknown)
int MaxCount();
int MaxCountLimit();
void SetMaxCount(int count);

// "Use target as cap": the limiter in use holds the final FPS at the target
bool TargetAsCap();
void SetTargetAsCap(bool cap);

// XeFG only
bool RoundingSupported();

// The cap the limiters apply now, 0 none (FrameLimit::targetFps)
float CapFps();

// External generator (the game's DLSSG): seen generating in the last second. multiplier: the one asked for
// (DLSSG.MultiFrameCount + 1), which the backend may not apply
bool ExternalGenerating(int* multiplier = nullptr);

// A present of ILION's wrapped swapchain (the game's present path when ILION has no FG output). Counted to measure the
// multiplier the game's DLSSG really applies: presents per DLSSG evaluation
void NoteWrappedPresent();

// The multiplier the game's DLSSG applies and where that comes from (0 when it doesn't generate): measured at the
// presents, else the one asked for. requested: the one asked for
int ExternalApplied(int* requested = nullptr, AppliedSource* source = nullptr);

// Streamline's numFramesActuallyPresented of the game's DLSSG: frames presented since the game's previous
// slDLSSGGetState, 0 none. The multiplier only if the game asks once per frame: shown, never used to limit
int ExternalReported();

// Real frames per second of the game's DLSSG (first evaluation of each frame), measured with the presents, 0 none
float ExternalRealFps();

// The game's DLSSG with a target cap: the real frames per second that hold it (target / applied multiplier), 0 none.
// framesToGenerate: the frames the current real frame generates (ILION Dynamic holds the cap with it), -1 unknown
float ExternalCapRealFps(int framesToGenerate = -1);

// The game's DLSSG runs in Streamline eDynamic (ILION's switch or the game's own choice): its backend chooses the
// multiplier toward the target, up to its own maximum. ILION's target cap stays off then: lowering the real frames would
// only make that controller raise the multiplier (a feedback loop up to the backend's maximum)
bool BackendDynamic();

// The game's DLSSG with a fixed multiplier and the target cap: suspended once the backend applies more frames than
// asked, until the asked count changes or the cap is turned off
bool ExternalCapSuspended();

// --- ILION Dynamic for the game's DLSSG (experimental) ------------------------------------------------------------
// Instead of the backend's eDynamic, the game's DLSSG stays in eOn and ILION picks numFramesToGenerate each real frame
// with its own instance of the R3 controller (XeFG_DynamicCount, unchanged), up to the maximum set by the user. With
// "Use target as cap" the real frames are held at target / the multiplier of that same frame, once per real frame:
// the backend has no controller of its own then, so lowering the real frames can't make it raise the multiplier.
// It stops (Refused) when the backend doesn't take the count asked for, or presents more frames than the maximum.

enum class ExternalMode
{
    Off,
    Ilion,  // ILION picks the count (eOn), real ceiling with "Use target as cap"
    Native, // the backend's eDynamic: its own count and maximum, the target is a goal, no ceiling
};

ExternalMode ExternalDynamicMode();
void SetExternalDynamicMode(ExternalMode mode);

// ILION's controller drives the game's DLSSG now (mode Ilion, the game's DLSSG in use, not refused)
bool IlionDrivesExternal();

// Interpolated frames ILION asks the game's DLSSG for (Streamline_Hooks: numFramesToGenerate)
int IlionExternalCount();

// Why ILION Dynamic stopped for the game's DLSSG (English, translated by the menu), nullptr when it didn't
const char* IlionExternalRefused();

// NGX DLSSG evaluation, first call of a real frame (game's present thread): the frames this one generates and the time
// FrameLimit::sleepExternalFg slept for it. Runs the controller; never calls Streamline itself
void ExternalRealFrame(int framesToGenerate, double sleptMs);

// Game's render thread, outside the NGX evaluation (slSetConstants / slEvaluateFeature hooks): sends a count ILION's
// controller changed, or the game's own options back after it stopped, through slDLSSGSetOptions
void ApplyPendingExternalCount();

Status Get();
} // namespace IlionDynamicMfg
