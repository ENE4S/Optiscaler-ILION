#pragma once

// ILION: one layer over the frame generation providers for Dynamic MFG and its FPS target, so the menu shows the same
// controls and the same state whichever provider generates. It maps to the settings each backend already reads; it
// adds no controller and no limiter of its own:
//   XeFG (ILION's output)      Dynamic = R3 controller (XeFG_DynamicMFG), count changed live by ILION
//   DLSSG of the game          Dynamic = Streamline eDynamic, run by the backend (NVIDIA or a replacement such as
//   (NvngxFG, DLSS Enabler...)  DLSS Enabler) only when it reports support; ILION sets mode, target and maximum
//   DLSSG (ILION's output)     Dynamic = Streamline eDynamic of ILION's own instance, when it reports support
//   FSR FG                     no Dynamic (one generated frame)
// The target cap goes to the one limiter already in use (Reflex, XeLL or OptiScaler's), as FrameLimit::targetFps().

namespace IlionDynamicMfg
{
enum class Provider
{
    None,
    XeFG,
    DlssgGame,   // the game's DLSSG through Streamline, generated by NVIDIA's runtime or a replacement
    DlssgOutput, // ILION's own DLSSG output
    FsrFg,       // ILION's FSR FG output (and reprojection)
};

enum class Gen
{
    Off,       // nothing generates
    Unknown,   // a generator is loaded but nothing tells whether it runs
    Detected,  // generation is asked for (ILION dispatches, or the game's DLSSG evaluates with frames to generate)
    Confirmed, // the provider reports frames it presented (XeFG present status, Streamline frames presented)
};

enum class Limiter
{
    None,
    Reflex,
    XeLL,
    OptiScaler,
};

struct Status
{
    Provider provider = Provider::None;
    const char* name = "";   // provider, as shown
    Gen gen = Gen::Off;
    bool own = false;        // generated by ILION's pipeline (else by the game / an external backend)
    int multiplier = 0;      // applied (own) or detected (external), 0 unknown
    float baseFps = 0.0f;
    bool baseMeasured = false;
    float finalFps = 0.0f;
    bool finalMeasured = false; // else estimated as base x multiplier
    Limiter limiter = Limiter::None;
    float limitFps = 0.0f;   // final frames per second the limiter holds, 0 none
};

Provider Current();

// Dynamic for the current provider: whether it can run, and why not (English, translated by the menu)
bool DynamicSupported(const char** reason = nullptr);
bool DynamicEnabled();
void SetDynamicEnabled(bool enabled);

// Final FPS target shared by every provider (0 = automatic where the provider has one)
float TargetFps();
void SetTargetFps(float fps);

// Highest multiplier as interpolated frames (1 = 2X), and the most the provider admits now (0 = unknown)
int MaxCount();
int MaxCountLimit();
void SetMaxCount(int count);

// "Use target as cap": the limiter in use holds the final FPS at the target
bool TargetAsCap();
void SetTargetAsCap(bool cap);

// XeFG only
bool RoundingSupported();

// The cap the limiters apply now, 0 none (FrameLimit::targetFps)
float CapFps();

// External generator (the game's DLSSG): seen generating in the last second
bool ExternalGenerating(int* multiplier = nullptr);

// A present of ILION's wrapped swapchain (the game's present path when ILION has no FG output)
void NoteWrappedPresent();
// For OptiScaler's limiter at the wrapped swapchain with the game's DLSSG generating: how many presented frames one
// limited present stands for. The multiplier when that swapchain sees only the game's frames, 1 when it sees every
// presented frame; measured from its presents per DLSSG evaluation (1 until measured)
int ExternalLimiterFactor();

Status Get();
} // namespace IlionDynamicMfg
